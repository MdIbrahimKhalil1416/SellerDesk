package com.sellerdesk.product.model;

import java.util.LinkedHashMap;
import java.util.Map;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import lombok.ToString;
import org.springframework.data.mongodb.core.mapping.Field;
import org.springframework.data.mongodb.core.mapping.FieldType;

/**
 * One sellable version of a product, e.g. "Red / M" (docs/modules/PRODUCT.md §2). Embedded in
 * the product document.
 *
 * <p>Never removed, only deactivated: orders and stock movements reference {@code variantId}
 * forever.
 */
@Getter
@Setter
@NoArgsConstructor
@ToString
public class Variant {

    /** Generated by the app ({@code new ObjectId()}), stable forever. */
    @Field(targetType = FieldType.OBJECT_ID)
    private String variantId;

    /** Uppercase, unique per shop, never changed after creation. */
    private String sku;

    private String name;

    /** e.g. {@code {"Color": "Red", "Size": "M"}}. Insertion order is kept for the default name. */
    private Map<String, String> attributes = new LinkedHashMap<>();

    /** Poisha. */
    private long price;

    /** Poisha, optional. Shown only to users with PRODUCT_EDIT or REPORT_VIEW. */
    private Long costPrice;

    /** {@code null} = use the shop's default. */
    private Integer lowStockThreshold;

    private boolean active;

    /** Written by Inventory only (except the zeros on create). */
    private VariantStock stock = VariantStock.empty();
}
