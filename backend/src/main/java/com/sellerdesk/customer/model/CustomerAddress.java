package com.sellerdesk.customer.model;

import com.sellerdesk.common.model.DeliveryZone;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import lombok.ToString;
import org.springframework.data.mongodb.core.mapping.Field;
import org.springframework.data.mongodb.core.mapping.FieldType;

/**
 * One saved address of a customer (docs/modules/CUSTOMER.md §2). The fields of the shared
 * {@code Address} plus a stable {@code addressId}, an optional {@code label} and the
 * {@code isDefault} mark (exactly one address is default when there is at least one).
 */
@Getter
@Setter
@NoArgsConstructor
@ToString
public class CustomerAddress {

    /** Generated by the app ({@code new ObjectId()}), never changes. */
    @Field(targetType = FieldType.OBJECT_ID)
    private String addressId;

    /** e.g. "Home", "Office". Optional. */
    private String label;

    /** Full address (house, road, area): free text. */
    private String line;

    /** Thana / upazila. Optional. */
    private String area;

    private String district;

    /** Decides the default delivery charge. */
    private DeliveryZone zone;

    /** Landmark. Optional. */
    private String note;

    @Field("isDefault")
    private boolean isDefault;

    /** Deep copy, so a changed list never shares objects with the loaded one. */
    public CustomerAddress copy() {
        CustomerAddress c = new CustomerAddress();
        c.setAddressId(addressId);
        c.setLabel(label);
        c.setLine(line);
        c.setArea(area);
        c.setDistrict(district);
        c.setZone(zone);
        c.setNote(note);
        c.setDefault(isDefault);
        return c;
    }
}
